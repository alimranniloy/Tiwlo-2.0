export const DEFAULT_COUNTRY: CountryOption = COUNTRIES[0];

export function findCountry(value?: string | null): CountryOption | undefined {
  if (!value) return undefined;
  const clean = String(value).trim().toLowerCase();
  if (!clean) return undefined;
  return (
    COUNTRIES.find((c) => c.name.toLowerCase() === clean) ||
    COUNTRIES.find((c) => c.code.toLowerCase() === clean) ||
    COUNTRIES.find((c) => (c.aliases || '').toLowerCase().includes(clean))
  );
}

export function searchCountries(query = ''): CountryOption[] {
  const clean = String(query || '').trim().toLowerCase();
  if (!clean) return COUNTRIES;
  return COUNTRIES.filter((c) =>
    `${c.name} ${c.code} ${c.dial} ${c.aliases || ''}`.toLowerCase().includes(clean)
  );
}
